/**
 * 记录时间口径（spec §4.2 ⑤-c 修订版）的**说明与补充导出**，供票 5/6/8 的重建面消费。
 *
 * ⚠️ **生成点不在本文件**：`nowIso` 是 `time.ts` 的**转出口**（re-export），实现只有一份。
 * 本模块曾自带一份逐字相同的实现，两处都自称「唯一生成点」——正是 ⑤-c「统一 helper」
 * 要消灭的平行真相源形态，只是落在 helper 层。方向判据：`time.ts` 是票 5 已收口进 dev
 * 的已审面，改它等于把本票的 diff 骑进已审代码；`clock.ts` 是本票新文件，故收口在这边。
 * 两模块**要不要合并成一个**（消费面今天仍分两路：`clock.js` = 4 个 repository + eval 侧，
 * `time.js` = messages/sessions 服务面）留给票 8 收口时一并审，本票只保证**只有一份实现**。
 *
 * 口径：ISO 8601 UTC 毫秒（`2026-09-17T08:30:00.123Z`）。定宽格式的字典序 = 时间序，
 * 索引/排序/字符串比较一律正确；JS 全栈 `new Date().toISOString()` 零转换。
 *
 * **为什么不在 SQL 里生成**：SQLite 的 `datetime('now')` 只有**秒级**精度，落进本口径
 * 的列就是把精度降档（同一秒内的两行永远分不出先后）；且它产出的是
 * `YYYY-MM-DD HH:MM:SS`，与 ISO 字符串**混比会错序**（`'T'` > `' '`，同日 ISO 恒大于
 * 秒级串）。⑤-b 的**目标**口径是全库时间列 ISO 毫秒（**已达标的只是已迁表**，见下），
 * SQL 侧生成 = 每写一行就埋一个格式混比。
 *
 * **为什么不在 DDL 里挂 DEFAULT**：DEFAULT 是「调用方忘了传也照样成功」的静默兜底，
 * 而漏传恰恰是本口径最该响亮报错的形态——故重建后的表**一律不挂时间 DEFAULT**，
 * 漏传直接撞 `NOT NULL` 约束。
 *
 * **例外（事件时间）**：语义是「事情发生时刻」的列（如 `started_at`/`ended_at`）允许
 * 调用方显式传入，命名必须体现事件语义——但取值仍必须走本口径。
 */
export { nowIso } from './time.js'

/**
 * 把「记录时间」串归一成 ISO 毫秒（**幂等**：已是 ISO 的一律原样返回）。
 *
 * **过渡期专用**，用在**跨表比较的边界**上：每张表是**各自的重建票**把它迁到 ISO 的——
 * 票 5 = `messages`，票 6 批一 = `execution_logs` / flow 系 / `review_verdicts` 等；
 * 而 `sessions` / `session_read_state` / `agents` / `episodes` / `knowledge` / `settings`
 * 的列**仍是秒级** `datetime('now')` 产物（随各自重建票迁移，如 `sessions` 系归票 8）。
 * 跨表比较时一侧 ISO、一侧秒级 ⇒ ISO 串首位 `T`(0x54) 恒大于秒级串首位空格(0x20)，
 * 「严格晚于 since」于是**恒真**：锚被复用前的历史判词会被算进本条链（判词归属错，
 * 静默）。故比较前把入参归一，两侧同口径。
 *
 * **两侧都迁完之后也不要删**：`toIsoMs` 对不匹配实测形态的取值是**原样保留**（不落
 * NULL，见 `db/migrations.ts`）⇒ 列里可能有非 ISO 残值；老库的混合态也仍在。留着它，
 * 对已是 ISO 的值恒等，对残值仍兜得住。
 *
 * ⚠️ **本函数与 `time.ts::toIsoDb` 同职责但识别面更窄，两者不可互换**（审查 P3-2 已挂票 8
 * 裁决「要不要合并回单口径」，本票不改行为、只在票 8 动刀前把分歧**实测**钉在这里，免得
 * 被当成同一把尺子用）：
 *
 * | 入参 | `normalizeIsoMs` | `toIsoDb` | 判据差在哪 |
 * | --- | --- | --- | --- |
 * | `2026-09-17 08:30:00` | `…T08:30:00.000Z` | 同 | 无差 |
 * | `2026-09-17 08:30:00.500` | **原样透传** | `…T08:30:00.500Z` | 本函数正则不认小数秒 |
 * | `2026-09-17T08:30:00Z` | **原样透传** | `…T08:30:00.000Z` | 本函数只认空格分隔 |
 * | `2026-09-17T08:30:00.123Z` | 原样透传 | 同 | 无差 |
 *
 * 中间两行是**真分歧**，不是措辞差：`'Z'`(0x5A) > `'.'`(0x2E) ⇒ 省略毫秒的 ISO 串在字符串
 * 比较下**大于**同一时刻的 `.000Z`，边界行会判反。第三行尤其要留意——`time.ts` 自己的
 * 注释就写着「省略毫秒是**常客**：票 5 之前本仓 API 的 `createdAt` 就是这个形状，客户端把
 * 它原样回传当窗口参数」。
 *
 * **今天未触发（实测，2026-09-18）**：对两库（`cat-study.db` / `cat-study-dev.db`）逐时间列
 * 取 **DISTINCT 值的形态普查**，`SEC_DOT`（空格+小数秒）与 `ISO_NO_MS`（ISO 省略毫秒）
 * **各 0 例**；非 ISO 值只有三类——空格整秒（34 列）、`chunks.date` 的纯日期、以及两类
 * **按列名误捕的非时间列**（`sessions.handoff_from` 存会话 id、`retrieval_candidates.status_at_query`
 * 存状态值）。故本分歧不阻塞本票；但票 8 合口径时必须按上表核一遍**谁归一谁**，
 * 且**别把这两列算进「已迁/未迁」的计数**（按名匹配在「列名」这一步就有假阳性）。
 */
export function normalizeIsoMs(value: string): string {
  return /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(value)
    ? `${value.replace(' ', 'T')}.000Z`
    : value
}

/**
 * `days` 天前的 ISO 毫秒时刻——时间窗比较点的**新口径参数**。
 *
 * 旧写法 `col >= datetime('now', '-N days')` 产出秒级串，与 ISO 列比较即格式混比：
 * 同一天里 ISO 串（首位 `T`）恒大于秒级串（首位空格）⇒ 窗口**静默放大**（把窗口外的
 * 行算进来）。切口径时这类比较点必须同批换，不能留半套。
 */
export function isoDaysAgo(days: number, from: number = Date.now()): string {
  return new Date(from - days * 86_400_000).toISOString()
}
